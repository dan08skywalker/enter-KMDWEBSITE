import { useMemo, useState } from "react";
import { BarChart3 } from "lucide-react";
import { useMemberLedger } from "@/hooks/use-member-ledger";
import { usePointRate } from "@/hooks/use-point-rate";
import { PageHeader } from "@/components/kmd/page-header";
import { StatCard } from "@/components/kmd/stat-card";
import { DataTable, type Column } from "@/components/kmd/data-table";
import { EmptyState } from "@/components/kmd/empty-state";
import { StatusBadge } from "@/components/kmd/status-badge";
import { FilterBar, SearchInput, SelectFilter } from "@/components/kmd/filter-bar";
import { Points } from "@/components/kmd/amount";
import { Progress } from "@/components/ui/progress";
import { formatDateTime, formatPeso, formatPoints, toNumber } from "@/lib/kmd/format";
import { ledgerStatus } from "@/lib/kmd/labels";
import { UNILEVEL_LEVELS } from "@/lib/kmd/constants";
import type { PointLedgerRow } from "@/lib/kmd/types";

export default function MemberUnilevelEarnings() {
  const rate = usePointRate();
  const ledger = useMemberLedger();
  const [level, setLevel] = useState("all");
  const [status, setStatus] = useState("all");
  const [product, setProduct] = useState("all");
  const [search, setSearch] = useState("");

  const unilevelRows = useMemo(
    () => ledger.pointRows.filter((row) => row.transaction_type === "UNILEVEL_BONUS"),
    [ledger.pointRows],
  );

  const levelTotals = useMemo(() => {
    return UNILEVEL_LEVELS.map((value) => {
      const rows = unilevelRows.filter((row) => row.unilevel_level === value);
      return {
        level: value,
        points: rows.reduce((sum, row) => sum + toNumber(row.total_points), 0),
        entries: rows.length,
      };
    });
  }, [unilevelRows]);

  const maxLevelPoints = Math.max(1, ...levelTotals.map((entry) => entry.points));

  const monthPoints = useMemo(() => {
    const monthStart = new Date();
    monthStart.setDate(1);
    monthStart.setHours(0, 0, 0, 0);
    return unilevelRows
      .filter((row) => new Date(row.created_at) >= monthStart && row.status === "posted")
      .reduce((sum, row) => sum + toNumber(row.total_points), 0);
  }, [unilevelRows]);

  const products = useMemo(
    () => Array.from(new Set(unilevelRows.map((row) => row.product_name).filter(Boolean))) as string[],
    [unilevelRows],
  );

  const filtered = useMemo(() => {
    const needle = search.trim().toLowerCase();
    return unilevelRows.filter((row) => {
      if (level !== "all" && String(row.unilevel_level) !== level) return false;
      if (status !== "all" && row.status !== status) return false;
      if (product !== "all" && row.product_name !== product) return false;
      if (needle) {
        const haystack = `${row.transaction_id} ${row.order_id ?? ""} ${row.buyer_member_code ?? ""}`.toLowerCase();
        if (!haystack.includes(needle)) return false;
      }
      return true;
    });
  }, [unilevelRows, level, status, product, search]);

  const columns: Column<PointLedgerRow>[] = [
    { key: "date", header: "Date", cell: (row) => formatDateTime(row.created_at) },
    {
      key: "txn",
      header: "Transaction ID",
      cell: (row) => <span className="font-mono text-xs">{row.transaction_id}</span>,
    },
    {
      key: "order",
      header: "Order ID",
      cell: (row) => (
        <span className="font-mono text-xs">{row.order_id ? `${row.order_id.slice(0, 8)}\u2026` : "\u2014"}</span>
      ),
    },
    { key: "buyer", header: "Buyer", cell: (row) => <span className="font-mono text-xs">{row.buyer_member_code ?? "\u2014"}</span> },
    { key: "product", header: "Product", cell: (row) => row.product_name ?? "\u2014" },
    { key: "sku", header: "SKU", cell: (row) => <span className="font-mono text-xs">{row.sku ?? "\u2014"}</span> },
    { key: "qty", header: "Qty", cell: (row) => row.quantity ?? "\u2014", className: "text-right" },
    {
      key: "level",
      header: "Level",
      cell: (row) => <StatusBadge label={`Level ${row.unilevel_level ?? "\u2014"}`} tone="gold" />,
    },
    { key: "perUnit", header: "Points / Unit", cell: (row) => formatPoints(row.points_per_unit), className: "text-right" },
    {
      key: "total",
      header: "Total Points",
      cell: (row) => <Points value={row.total_points} direction={row.direction} showSign />,
      className: "text-right",
    },
    {
      key: "status",
      header: "Status",
      cell: (row) => {
        const descriptor = ledgerStatus(row.status);
        return <StatusBadge label={descriptor.label} tone={descriptor.tone} />;
      },
    },
  ];

  return (
    <>
      <PageHeader
        title="Unilevel Earnings"
        description="Level 1 to Level 5 bonuses generated by qualified purchases in your team."
      />

      <div className="grid gap-4 sm:grid-cols-3">
        <StatCard
          label="Available Points"
          value={formatPoints(ledger.availablePoints)}
          hint={formatPeso(ledger.availablePoints, rate)}
          icon={BarChart3}
          accent="gold"
          loading={ledger.loading}
        />
        <StatCard
          label="This Month"
          value={formatPoints(monthPoints)}
          hint={formatPeso(monthPoints, rate)}
          accent="primary"
          loading={ledger.loading}
        />
        <StatCard
          label="Lifetime Unilevel"
          value={formatPoints(ledger.lifetimePoints)}
          hint={`${unilevelRows.length} ledger entries`}
          accent="success"
          loading={ledger.loading}
        />
      </div>

      <section className="kmd-panel p-5">
        <h2 className="text-sm font-semibold">Points earned per level</h2>
        <p className="mt-1 text-xs text-muted-foreground">
          Levels 3, 4 and 5 pay only once an administrator configures their values in Reward
          Configuration.
        </p>
        <div className="mt-4 space-y-4">
          {levelTotals.map((entry) => (
            <div key={entry.level}>
              <div className="flex items-center justify-between text-xs">
                <span className="font-semibold">Level {entry.level}</span>
                <span className="tabular-nums text-muted-foreground">
                  {formatPoints(entry.points)} pts &middot; {formatPeso(entry.points, rate)} &middot;{" "}
                  {entry.entries} {entry.entries === 1 ? "entry" : "entries"}
                </span>
              </div>
              <Progress
                value={(entry.points / maxLevelPoints) * 100}
                className="mt-2 h-2"
              />
            </div>
          ))}
        </div>
      </section>

      <FilterBar>
        <SearchInput
          value={search}
          onChange={setSearch}
          placeholder="Search order, transaction or buyer"
        />
        <SelectFilter
          value={level}
          onChange={setLevel}
          allLabel="All levels"
          options={UNILEVEL_LEVELS.map((value) => ({ value: String(value), label: `Level ${value}` }))}
        />
        <SelectFilter
          value={product}
          onChange={setProduct}
          allLabel="All products"
          options={products.map((value) => ({ value, label: value }))}
        />
        <SelectFilter
          value={status}
          onChange={setStatus}
          allLabel="All statuses"
          options={[
            { value: "posted", label: "Posted" },
            { value: "pending", label: "Held" },
            { value: "reversed", label: "Reversed" },
          ]}
        />
      </FilterBar>

      <DataTable
        columns={columns}
        rows={filtered}
        rowKey={(row) => row.id}
        loading={ledger.loading}
        empty={
          <EmptyState
            icon={BarChart3}
            title="No unilevel entries"
            description="Once a team member's purchase is qualified, the bonus for each eligible level appears here."
          />
        }
      />
    </>
  );
}
